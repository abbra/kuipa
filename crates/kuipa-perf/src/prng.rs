//! Deterministic pseudo-random synthesis for benchmark fixtures.
//!
//! The workspace patches `rand` to the OpenSSL shim, which has no seedable
//! generator, so fixtures need their own.  `SplitMix64` is the reference
//! implementation from Stockfish: six lines, no dependencies, and identical
//! output on every platform, which is what makes a benchmark run comparable
//! across machines.

/// A deterministic `SplitMix64` generator.
pub struct SplitMix64 {
    state: u64,
}

impl SplitMix64 {
    /// Create a generator at `seed`.
    #[must_use]
    pub fn new(seed: u64) -> Self {
        Self { state: seed }
    }

    /// The next 64-bit value.
    pub fn next_u64(&mut self) -> u64 {
        self.state = self.state.wrapping_add(0x9e37_79b9_7f4a_7c15);
        let mut z = self.state;
        z = (z ^ (z >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
        z ^ (z >> 31)
    }

    /// The next value reduced to `u32`.
    pub fn next_u32(&mut self) -> u32 {
        (self.next_u64() >> 32) as u32
    }

    /// Fill `out` with generated bytes, little-endian per word.
    pub fn fill_bytes(&mut self, out: &mut [u8]) {
        for chunk in out.chunks_mut(8) {
            let word = self.next_u64().to_le_bytes();
            chunk.copy_from_slice(&word[..chunk.len()]);
        }
    }

    /// A byte string of `len` generated bytes.
    pub fn bytes(&mut self, len: usize) -> Vec<u8> {
        let mut out = vec![0u8; len];
        self.fill_bytes(&mut out);
        out
    }

    /// A stable hash of `data`, for deriving fixture keys from names.
    #[must_use]
    pub fn hash(data: &[u8]) -> u64 {
        let mut h = 0xcbf2_9ce4_8422_2325_u64;
        for b in data {
            h = (h ^ u64::from(*b)).wrapping_mul(0x1000_0000_1b32_1115);
        }
        h
    }
}

#[cfg(test)]
mod tests {
    use super::SplitMix64;

    #[test]
    fn deterministic_sequence() {
        let mut a = SplitMix64::new(42);
        let mut b = SplitMix64::new(42);
        for _ in 0..16 {
            assert_eq!(a.next_u64(), b.next_u64());
        }
        assert_ne!(SplitMix64::new(1).next_u64(), SplitMix64::new(2).next_u64());
    }

    #[test]
    fn fill_covers_odd_lengths() {
        let mut r = SplitMix64::new(7);
        let mut out = vec![0u8; 13];
        r.fill_bytes(&mut out);
        assert!(out.iter().any(|&b| b != 0));
        assert_eq!(r.bytes(0).len(), 0);
    }

    #[test]
    fn hash_stable() {
        assert_eq!(
            SplitMix64::hash(b"web1.example.test"),
            SplitMix64::hash(b"web1.example.test")
        );
        assert_ne!(SplitMix64::hash(b"a"), SplitMix64::hash(b"b"));
    }
}
