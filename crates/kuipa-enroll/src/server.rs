    /// `GET /ipa/ku/adv`: the advertisement, re-signed at half life.  Its
    /// delegation carries one signature: by the first of `wanted` (the
    /// anchors the client pins) that signed it, else by this server's own
    /// anchor (§4.3); for a client that pins only rotated anchors, with the
    /// successions that lead to the signer (§4.7).  For a client that
    /// pins a vouch head (§4.9), the delegation carries a head proof
    /// instead: no signature, no anchor key.
    ///
    /// # Errors
    ///
    /// A signing error.
    pub fn advertisement(&self, wanted: &[Thumbprint]) -> crate::Result<SignedAdvertisement> {
        self.advertisement_with_heads(wanted, &[])
    }

    /// [`advertisement`](Self::advertisement) with the client's pinned
    /// vouch heads (§4.9): a head that matches one of this server's
    /// published vouches turns into a head proof, served alone.
    ///
    /// # Errors
    ///
    /// A signing error, or a hash error building the proof.
    pub fn advertisement_with_heads(
        &self,
        wanted: &[Thumbprint],
        heads: &[HeadPin],
    ) -> crate::Result<SignedAdvertisement> {
        let now = unix_seconds(SystemTime::now());
        let published = self.published();
        let epoch = published
            .epoch
            .last()
            .and_then(|e| e.statement().ok())
            .and_then(|s| Some((s.seq(), s.head().ok()?)));
        // One head proof per pinned head that this server's vouches can
        // make (§1.4: the server tries each pinned head in turn): a host
        // with several pinned anchors — frozen ones especially (§2) —
        // needs *each* of its heads to prove the claim, so the answer
        // carries every proof, not just the first.
        let mut delegation = published.delegation.clone();
        let claim = delegation.claim().ok();
        if let Some(claim) = claim.as_ref() {
            for head in heads {
                let Some(vouch) = published.vouches.get(&head.anchor) else {
                    continue;
                };
                if let Some(proof) =
                    vouch.head_proof(claim, &head.anchor, (head.size, head.root))?
                {
                    delegation.add_head_proofs([proof]);
                }
            }
        }
        let delegation = delegation.select_with_heads(wanted, heads);
        let signer = (
            delegation.signers(&self.policy).first().copied(),
            delegation
                .successions()
                .first()
                .and_then(|s| s.statement().ok())
                .map(|s| s.old),
            epoch,
            // A cache key: any one hash will do.
            Some(merkle::leaf_hash(
                merkle::TreeHash::Sha384,
                delegation.to_json().as_bytes(),
            )?),
        );
        if let Some((adv, iat)) = published.advertisements.get(&signer)
            && now.saturating_sub(*iat) < ADVERTISEMENT_VALIDITY / 2
        {
            return Ok(adv.clone());
        }
        let info = RealmInfo {
            anchors: published.anchors.clone(),
            heads: {
                // HashMap order is arbitrary; sort so the same published
                // state always signs the same advertisement bytes.
                let mut heads: Vec<HeadPin> = published
                    .vouches
                    .iter()
                    .map(|(a, v)| HeadPin {
                        anchor: *a,
                        size: v.vouch().size,
                        root: v.vouch().root,
                    })
                    .collect();
                heads.sort_by_key(|h| h.anchor);
                heads
            },
            trusts: published.trusts.clone(),
            ..self.info.clone()
        };
        let adv = self.keys.advertisement(
            &info,
            &delegation,
            now,
            now + ADVERTISEMENT_VALIDITY,
            epoch,
        )?;
        let mut p = self
            .published
            .write()
            .unwrap_or_else(PoisonError::into_inner);
        if p.delegation == published.delegation
            && p.anchors == published.anchors
            && p.trusts == published.trusts
            && p.epoch == published.epoch
            && p.vouches == published.vouches
        {
            p.advertisements.insert(signer, (adv.clone(), now));
        }
        Ok(adv)
    }

    /// Answer a join, rekey, stage or registration request received at the
    /// endpoint of `request.operation()`.
    ///
    /// # Errors
    ///
    /// A [`Refusal`] for any failure.
    pub fn handle(
        &self,
        request: &Request,
        directory: &dyn Directory,
    ) -> Result<Response, Refusal> {
        if request.realm() != self.info.realm {
            return Err(Refusal::because("wrong realm"));
        }
        let key = self
            .keys
            .join_key(request.kid())
            .filter(|k| k.public().alg() == request.alg())
            .ok_or_else(|| Refusal::because("unknown join key"))?;
        let ss = key.decapsulate(request.ciphertext())?;
        let t = request.transcript(self.keys.signing.public().thumbprint())?;
        let body = request.open_body(ss.as_ref(), &t)?;
        let cb = channel_binding(request.alg(), ss.as_ref(), &t)?;
        let fqdn = request.fqdn();
        let enctypes = request.enctypes();
        let token = body.authenticator.as_ref();
        let principal = Principal::host(fqdn, &self.info.realm);
        let mut kerberos = None;

        let payload = match (request.operation(), request.auth_type()) {
            (Operation::Join, AuthType::Otp) => {
                let keytab = directory
                    .join_with_otp(fqdn, token, enctypes)
                    .map_err(Refusal)?;
                self.enrollment(keytab, directory)?.to_bytes()?
            }
            (Operation::Join, AuthType::Voucher) => {
                let voucher = Voucher::parse(token)?;
                let key = self
                    .keys
                    .vouchers
                    .iter()
                    .find(|k| k.thumbprint() == voucher.key())
                    .ok_or_else(|| Refusal::because("unknown voucher key"))?;
                let ephemeral = crate::voucher::binding(request.ephemeral_key())?;
                let now = unix_seconds(SystemTime::now());
                let claims = voucher.verify(key, &self.info.realm, fqdn, &ephemeral, now)?;
                let lease = voucher_lease(claims, now, directory)?;
                let keytab = directory
                    .join_with_voucher(fqdn, &claims.hostgroup, voucher.salt(), enctypes, lease)
                    .map_err(Refusal)?;
                self.enrollment(keytab, directory)?.to_bytes()?
            }
            (Operation::Join, AuthType::Kerberos) => {
                let (keytab, binding) = directory
                    .join_with_gss(fqdn, token, &cb, enctypes)
                    .map_err(Refusal)?;
                kerberos = Some(binding);
                self.enrollment(keytab, directory)?.to_bytes()?
            }
            (Operation::Rekey, AuthType::Kerberos) => {
                let (keytab, binding) = directory
                    .rekey_with_gss(fqdn, token, &cb, enctypes)
                    .map_err(Refusal)?;
                kerberos = Some(binding);
                self.enrollment(keytab, directory)?.to_bytes()?
            }
            (Operation::Stage, AuthType::Kerberos) => {
                let (payload, binding) = self.stage(request, &body, &cb, directory)?;
                kerberos = Some(binding);
                payload
            }
            (Operation::Register, AuthType::Kerberos) => {
                return self.register(request, ss.as_ref(), &t, &body, directory);
            }
            (Operation::Seal, AuthType::Kerberos) => {
                return self.seal_op(request, ss.as_ref(), &t, &body, directory);
            }
            (Operation::Keys, AuthType::Kerberos) => {
                return self.keys_op(request, ss.as_ref(), &t, &body, directory);
            }
            (Operation::Tlog, AuthType::Kerberos) => {
                return self.tlog_op(request, ss.as_ref(), &t, &body, directory);
            }
            (Operation::Sign, AuthType::Kerberos) => {
                return self.sign_op(request, ss.as_ref(), &t, &body, directory);
            }
            (Operation::Pins, AuthType::Kerberos) => {
                return self.pins_op(request, ss.as_ref(), &t, &body, directory);
            }
            (op, auth) => {
                return Err(Refusal::because(format!(
                    "{op:?} with {auth:?} is not supported"
                )));
            }
        };
        if !body.registrations.is_empty() && request.operation() != Operation::Stage {
            directory
                .register_escrow(&principal, &body.registrations)
                .map_err(Refusal)?;
        }
        Ok(request.respond(ss.as_ref(), &t, kerberos.as_ref(), payload.as_ref())?)
    }

    /// Stage a host (§8.3): keys from the directory, packed into a bundle
    /// for the recipient the parameters name.
    fn stage(
        &self,
        request: &Request,
        body: &RequestBody,
        cb: &[u8; 32],
        directory: &dyn Directory,
    ) -> Result<(native_ossl::util::SecretBuf, KerberosBinding), Refusal> {
        let params = StageParams::from_bytes(&body.extra)?;
        let staged = Staged {
            not_after: params.not_after,
            recipient: params.recipient.as_ref().map(|k| *k.kid()),
        };
        let (keytab, binding) = directory
            .stage_with_gss(
                request.fqdn(),
                body.authenticator.as_ref(),
                cb,
                request.enctypes(),
                &staged,
            )
            .map_err(Refusal)?;
        let enrollment = self.enrollment(keytab, directory)?;
        let recipient = match (params.mode, &params.recipient) {
            (crate::bundle::Mode::MachineKey, Some(k)) => Recipient::MachineKey(k),
            (crate::bundle::Mode::Secret, _) => Recipient::Secret,
            _ => Recipient::SignedOnly,
        };
        let now = unix_seconds(SystemTime::now());
        let (bundle, secret) = Bundle::create(
            &self.keys,
            &self.delegation().select(&[]),
            request.alg(),
            recipient,
            &enrollment,
            now,
            params.not_after,
        )?;
        let mut w = Writer::new(STAGE_MAGIC);
        w.bytes(&bundle.to_bytes())
            .bytes(secret.as_ref().map_or(&[][..], |s| s.as_bytes()));
        Ok((native_ossl::util::SecretBuf::new(w.finish()), binding))
    }

    /// Answer a registration (§7.5): change the bindings of its principal
    /// as the directory authorises, and acknowledge.
    fn register(
        &self,
        request: &Request,
        ss: &[u8],
        t: &[u8],
        body: &RequestBody,
        directory: &dyn Directory,
    ) -> Result<Response, Refusal> {
        let params = RegisterParams::from_bytes(&body.extra)?;
        if params.principal.realm() != self.info.realm {
            return Err(Refusal::because("wrong realm"));
        }
        let cb = channel_binding(request.alg(), ss, t)?;
        let token = body.authenticator.as_ref();
        let binding = directory
            .register_with_gss(&params, &body.registrations, token, &cb)
            .map_err(Refusal)?;
        Ok(request.respond(ss, t, Some(&binding), &params.acknowledgement())?)
    }

    /// Answer a seal operation (§7.6): authenticate the caller by their
    /// ticket, check their role in the seal, apply the owner's limits,
    /// store, and answer with signed descriptors.
    fn seal_op(
        &self,
        request: &Request,
        ss: &[u8],
        t: &[u8],
        body: &RequestBody,
        directory: &dyn Directory,
    ) -> Result<Response, Refusal> {
        let cb = channel_binding(request.alg(), ss, t)?;
        let accepted = directory
            .accept_user(body.authenticator.as_ref(), &cb)
            .map_err(Refusal)?;
        let caller: Principal = accepted.principal.parse()?;
        if caller.realm() != self.info.realm {
            return Err(Refusal::because("wrong realm"));
        }
        let op = SealOp::from_bytes(&body.extra)?;
        let now = unix_seconds(SystemTime::now());
        let mut event = seal_event(&op);
        // Whoever loses a device or their membership must not open files
        // sealed for offline sessions from now on: a new epoch starts.
        let rotate = matches!(op, SealOp::RemoveDevice { .. } | SealOp::Unshare { .. });
        let mut receipts = Vec::new();
        // What the operations that concern no descriptor answer.
        let mut side = Reply::default();
        let (seals, session, released) = match op {
            op @ (SealOp::Request { .. }
            | SealOp::Pending { .. }
            | SealOp::Approve { .. }
            | SealOp::Deny { .. }
            | SealOp::EscrowCode { .. }
            | SealOp::RecoverCode
            | SealOp::Deposit { .. }
            | SealOp::Deposits { .. }
            | SealOp::FetchDeposit { .. }
            | SealOp::RetireDeposit { .. }
            | SealOp::RecoverySettings
            | SealOp::DeviceKey { .. }
            | SealOp::Deliver { .. }
            | SealOp::Passkeys) => {
                side = self.side_op(&caller, op, now, directory)?;
                (Vec::new(), None, None)
            }
            op @ SealOp::Unlock { .. } => {
                let started = self.start_session(&caller, &op, &cb, now, directory)?;
                receipts.extend(started.receipts);
                // Nothing is released before the answer, which waits for
                // the record.
                if let Some((action, device)) = event.take() {
                    receipts.extend(self.record_change(&started.seal, action, device)?);
                }
                (vec![started.seal], Some(started.token), started.released)
            }
            op => {
                // A change is recorded before the directory stores it, so a
                // failed append leaves the seal as it was.
                let mut record = |seal: &Seal| {
                    if let Some((action, device)) = event.take() {
                        receipts.extend(self.record_change(seal, action, device)?);
                    }
                    Ok(())
                };
                let mut seals = self.apply_seal_op(&caller, op, now, directory, &mut record)?;
                for v in &mut seals {
                    receipts.extend(self.settle_seal(v, now, rotate, directory)?);
                }
                (seals, None, None)
            }
        };
        let descriptors = self.public_descriptors(&seals, now, directory)?;
        receipts.append(&mut side.receipts);
        if receipts.len() > 255 {
            // The wire counts receipts in a `u8`; the committed change
            // stands and its log entries speak for the receipts that
            // do not fit.
            eprintln!(
                "kuipad: the reply carries {} receipts: 255 are sent",
                receipts.len()
            );
            receipts.truncate(255);
        }
        let reply = Reply {
            descriptors,
            session,
            released,
            receipts,
            ..side
        };
        Ok(request.respond(ss, t, Some(&accepted.binding), &reply.to_bytes()?)?)
    }

    /// Settle a seal a seal operation touched: whoever has no part in it
    /// any more (out of the group in IPA, or unshared) loses their
    /// devices, as a removal would, and its epochs move on — at once when
    /// `rotate` or someone left. Stores the seal if it changed and
    /// answers the receipts of the removals.
    fn settle_seal(
        &self,
        seal: &mut Seal,
        now: u64,
        rotate: bool,
        directory: &dyn Directory,
    ) -> Result<Vec<Receipt>, Refusal> {
        let gone = prune_departed(seal, directory)?;
        let mut receipts = Vec::new();
        for id in &gone {
            receipts.extend(self.record_change(
                seal,
                SealAction::RemoveDevice,
                Some(id.clone()),
            )?);
        }
        let rotated = self.maintain_epochs(seal, now, rotate || !gone.is_empty(), directory)?;
        if rotated || !gone.is_empty() {
            directory.seal_update(seal).map_err(Refusal)?;
        }
        Ok(receipts)
    }

    /// Sign the descriptors of `seals`, each for as long as its owner's
    /// limits allow. Descriptors carry each epoch's public key, never its
    /// slots.
    fn public_descriptors(
        &self,
        seals: &[Seal],
        now: u64,
        directory: &dyn Directory,
    ) -> Result<Vec<Descriptor>, Refusal> {
        let delegation = self.delegation();
        seals
            .iter()
            .map(|v| {
                let max_age = limits_for(&v.owner, directory)?.descriptor_age;
                let mut public = v.clone();
                for k in &mut public.session_keys {
                    k.slots.clear();
                }
                public.bindings.clear();
                Ok(Descriptor::sign(
                    &self.keys.signing,
                    &delegation,
                    &self.info.realm,
                    &public,
                    now,
                    max_age,
                )?)
            })
            .collect()
    }

    /// Answer a `keys` fetch (§18.2): authenticate the caller by their
    /// ticket, let the directory check the namespace policy (the server
    /// list and CA roles) and produce the value, and answer with it.
    fn keys_op(
        &self,
        request: &Request,
        ss: &[u8],
        t: &[u8],
        body: &RequestBody,
        directory: &dyn Directory,
    ) -> Result<Response, Refusal> {
        let cb = channel_binding(request.alg(), ss, t)?;
        let accepted = directory
            .accept_user(body.authenticator.as_ref(), &cb)
            .map_err(Refusal)?;
        let caller: Principal = accepted.principal.parse()?;
        if caller.realm() != self.info.realm {
            return Err(Refusal::because("wrong realm"));
        }
        let fetch = crate::keys::KeysFetch::from_bytes(&body.extra)?;
        let value = directory.fetch_key(&caller, &fetch).map_err(Refusal)?;
        self.record(
            Kind::KEYS_FETCH,
            caller.to_string().as_bytes(),
            &fetch
                .to_bytes()
                .map_err(|e| Refusal::because(e.to_string()))?,
        )?;
        let answer = crate::keys::KeysAnswer { value };
        let payload = answer
            .to_bytes()
            .map_err(|e| Refusal::because(e.to_string()))?;
        Ok(request.respond(ss, t, Some(&accepted.binding), &payload)?)
    }

    /// Answer a signing request (`DESIGN-sign.md`): authenticate the
    /// caller by their ticket, check the realm's signing policy against
    /// the caller and its groups, record the statement in the log — no
    /// log, no statement — and sign it with the log's position.
    fn sign_op(
        &self,
        request: &Request,
        ss: &[u8],
        t: &[u8],
        body: &RequestBody,
        directory: &dyn Directory,
    ) -> Result<Response, Refusal> {
        let cb = channel_binding(request.alg(), ss, t)?;
        let accepted = directory
            .accept_user(body.authenticator.as_ref(), &cb)
            .map_err(Refusal)?;
        let caller: Principal = accepted.principal.parse()?;
        if caller.realm() != self.info.realm {
            return Err(Refusal::because("wrong realm"));
        }
        if directory.principal_locked(&caller).map_err(Refusal)? {
            return Err(Refusal::because(format!("{caller} is locked or gone")));
        }
        let asked = crate::sign::Request::from_bytes(&body.extra)?;
        let groups = directory.principal_groups(&caller).map_err(Refusal)?;
        directory
            .sign_policy()
            .map_err(Refusal)?
            .check(&caller, &groups, &asked.purpose)?;
        let tree = self.tree_hash();
        if let Some(d) = asked.digests.iter().find(|d| !d.alg.fits(tree)) {
            return Err(Refusal::because(format!(
                "a {:?} digest is weaker than this server's {tree:?} (the crypto policy)",
                d.alg
            )));
        }
        let leaves = asked.leaves(tree)?;
        let batch_root = merkle::root(&leaves)?;
        let now = unix_seconds(SystemTime::now());
        let opening = Opening::new(
            Kind::STATEMENT,
            now,
            caller.to_string().as_bytes(),
            crate::sign::Statement::log_body(&asked.purpose, leaves.len() as u64, &batch_root, now),
        )?;
        let Some(appended) = self.ledger.append(opening).map_err(Refusal)? else {
            return Err(Refusal::because(
                "this server keeps no transparency log: it states nothing it cannot show",
            ));
        };
        let statement = crate::sign::Statement {
            realm: self.info.realm.clone(),
            principal: caller.to_string(),
            purpose: asked.purpose.clone(),
            batch_size: leaves.len() as u64,
            batch_root,
            iat: now,
            log: appended.log,
            index: appended.index,
        };
        let signed =
            crate::sign::SignedStatement::sign(&self.keys.signing, &self.delegation(), statement)?;
        let answer = crate::sign::Answer::new(&asked, signed)?;
        Ok(request.respond(ss, t, Some(&accepted.binding), &answer.to_bytes())?)
    }

