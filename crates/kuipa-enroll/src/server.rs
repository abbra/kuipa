/// Errors from a [`Directory`], kept for the log.
pub type DirectoryError = Box<dyn std::error::Error + Send + Sync>;

/// Staging details recorded on the host entry (§8.3).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Staged {
    /// When the staged keys expire (`krbPrincipalExpiration`).
    pub not_after: u64,
    /// Mode A: thumbprint of the recipient key.
    pub recipient: Option<tang_pqc::Thumbprint>,
}

/// A GSS-API token accepted for a principal (§7.6).
#[derive(Debug)]
pub struct Accepted {
    /// The client principal.
    pub principal: String,
    /// The binding both ends derive from the context.
    pub binding: KerberosBinding,
    /// The services a delegated ticket passed through (the PAC's S4U
    /// delegation info), empty for a ticket the principal obtained itself;
    /// `None` when the directory cannot tell (no PAC, or not read), which
    /// only `ticket.delegation = allow` accepts.
    pub transited: Option<Vec<String>>,
}

/// The directory operations behind the protocol, implemented by the daemon
/// over LDAPI and GSSAPI (§11.4).
///
/// Each method returns the host's new keys, generated by the directory
/// (`KEYTAB_GET` with server-side generation) for the intersection of
/// `enctypes` with the realm's allowed types.
pub trait Directory {
    /// Bind as the host with its OTP, join, and create keys.
    ///
    /// # Errors
    ///
    /// Any refusal; the reason is logged, never sent.
    fn join_with_otp(
        &self,
        fqdn: &str,
        otp: &[u8],
        enctypes: &[Enctype],
    ) -> Result<Keytab, DirectoryError>;

    /// Accept `token` with channel bindings `cb`, join as the caller.
    /// Returns the keys and the binding derived from the accepted context
    /// with [`crate::join::kerberos_prf_input`] (as for the other `_with_gss`
    /// methods).
    ///
    /// # Errors
    ///
    /// Any refusal.
    fn join_with_gss(
        &self,
        fqdn: &str,
        token: &[u8],
        cb: &[u8; 32],
        enctypes: &[Enctype],
    ) -> Result<(Keytab, KerberosBinding), DirectoryError>;

    /// Accept `token` from `host/<fqdn>` itself and rotate its keys.  If
    /// the host is staged, clear the staged state and the principal
    /// expiration (§8.5) and log the event.
    ///
    /// # Errors
    ///
    /// Any refusal.
    fn rekey_with_gss(
        &self,
        fqdn: &str,
        token: &[u8],
        cb: &[u8; 32],
        enctypes: &[Enctype],
    ) -> Result<(Keytab, KerberosBinding), DirectoryError>;

    /// Accept an administrator's `token`, create or reset the host entry,
    /// create keys and record `staged`.
    ///
    /// # Errors
    ///
    /// Any refusal.
    fn stage_with_gss(
        &self,
        fqdn: &str,
        token: &[u8],
        cb: &[u8; 32],
        enctypes: &[Enctype],
        staged: &Staged,
    ) -> Result<(Keytab, KerberosBinding), DirectoryError>;

    /// Replace the registered keytab escrow bindings of `principal`.
    ///
    /// # Errors
    ///
    /// Any failure.
    fn register_escrow(
        &self,
        principal: &Principal,
        bindings: &[BindingHash],
    ) -> Result<(), DirectoryError>;

    /// Is `binding` registered for `principal` in its `kind` set, and is
    /// the principal's entry enabled (not locked)?
    ///
    /// # Errors
    ///
    /// Any failure.
    fn escrow_allowed(
        &self,
        principal: &Principal,
        kind: escrow::Kind,
        binding: &BindingHash,
    ) -> Result<bool, DirectoryError>;

    /// Accept `token` from `params.principal` itself (any principal of the
    /// realm with an entry: host, service or user) and change its escrow
    /// bindings (§7.5): for [`escrow::Kind::Keytab`], `bindings` replace the
    /// keytab set; for [`escrow::Kind::File`], they join the file set and
    /// `params.retire` leaves it.
    ///
    /// # Errors
    ///
    /// Any refusal; by default registration outside a rekey is not
    /// supported.
    fn register_with_gss(
        &self,
        params: &RegisterParams,
        bindings: &[BindingHash],
        token: &[u8],
        cb: &[u8; 32],
    ) -> Result<KerberosBinding, DirectoryError> {
        let _ = (params, bindings, token, cb);
        Err("escrow registration outside a rekey is not supported by this directory".into())
    }

    /// Fetch a named secret for a `keys` operation's caller (§18.2):
    /// `principal` is the caller the token authenticated, and the value
    /// is the handler's output.  The policy check against the server
    /// list and CA roles is the directory's to make, against `cn=masters`
    /// in FreeIPA.
    ///
    /// # Errors
    ///
    /// Any refusal; by default the keys operation is not supported.
    fn fetch_key(
        &self,
        principal: &Principal,
        fetch: &crate::keys::KeysFetch,
    ) -> Result<Vec<u8>, DirectoryError> {
        let _ = (principal, fetch);
        Err("the keys operation is not supported by this directory".into())
    }

    /// The IPA CA chain (DER).
    ///
    /// # Errors
    ///
    /// Any failure.
    fn ca_certificates(&self) -> Result<Vec<Vec<u8>>, DirectoryError>;

    /// The realm's servers, for the client's configuration.
    ///
    /// # Errors
    ///
    /// Any failure.
    fn servers(&self) -> Result<Vec<String>, DirectoryError>;

    /// Accept a user's (or any principal's) GSS-API token bound to `cb`,
    /// for vault operations and the ticket factor (§7.6).
    ///
    /// # Errors
    ///
    /// Any refusal; by default vaults are not supported.
    fn accept_user(&self, token: &[u8], cb: &[u8; 32]) -> Result<Accepted, DirectoryError> {
        let _ = (token, cb);
        Err("vaults are not supported by this directory".into())
    }

    /// The realm's vault limits.
    ///
    /// # Errors
    ///
    /// Any failure.
    fn vault_limits(&self) -> Result<Limits, DirectoryError> {
        Ok(Limits::default())
    }

    /// The realm's signing policy (`DESIGN-sign.md`): who may sign for
    /// which purpose.
    ///
    /// # Errors
    ///
    /// Any failure; by default signing is not supported.
    fn sign_policy(&self) -> Result<crate::sign::SignPolicy, DirectoryError> {
        Err("signing is not supported by this directory".into())
    }

    /// The groups `principal` is a member of (user groups for a user,
    /// host groups for a host), directly or not: the directory's
    /// `memberOf`.
    ///
    /// # Errors
    ///
    /// Any failure; by default groups are not supported.
    fn principal_groups(&self, principal: &Principal) -> Result<Vec<String>, DirectoryError> {
        let _ = principal;
        Err("groups are not supported by this directory".into())
    }

    /// Store a new vault; refuse a name its owner already uses.
    ///
    /// # Errors
    ///
    /// Any failure; by default vaults are not supported.
    fn vault_add(&self, vault: &Vault) -> Result<(), DirectoryError> {
        let _ = vault;
        Err("vaults are not supported by this directory".into())
    }

    /// The vault `id`, if it exists.
    ///
    /// # Errors
    ///
    /// Any failure.
    fn vault_get(&self, id: &escrow::VaultId) -> Result<Option<Vault>, DirectoryError> {
        let _ = id;
        Ok(None)
    }

    /// Replace a stored vault (policy, devices, state).
    ///
    /// # Errors
    ///
    /// Any failure; by default vaults are not supported.
    fn vault_update(&self, vault: &Vault) -> Result<(), DirectoryError> {
        let _ = vault;
        Err("vaults are not supported by this directory".into())
    }

    /// The vaults `owner` owns.
    ///
    /// # Errors
    ///
    /// Any failure.
    fn vaults_of(&self, owner: &Principal) -> Result<Vec<Vault>, DirectoryError> {
        let _ = owner;
        Ok(Vec::new())
    }

    /// The vaults shared with `principal`, a member of `groups`: those
    /// whose managers or members hold any of
    /// [`Members::matching_entries`](crate::vault::Members::matching_entries).
    ///
    /// # Errors
    ///
    /// Any failure.
    fn vaults_shared_with(
        &self,
        principal: &Principal,
        groups: &[String],
    ) -> Result<Vec<Vault>, DirectoryError> {
        let _ = (principal, groups);
        Ok(Vec::new())
    }

    /// Count one release of vault `id` by `server` (§7.6.7), unless the
    /// vault's releases, summed over all servers, have reached `limit`:
    /// then count nothing and answer `false`.
    ///
    /// # Errors
    ///
    /// Any failure; by default only vaults without a limit are supported.
    fn vault_unlock(
        &self,
        id: &escrow::VaultId,
        server: &str,
        limit: Option<u64>,
    ) -> Result<bool, DirectoryError> {
        let _ = (id, server);
        match limit {
            None => Ok(true),
            Some(_) => Err("unlock limits are not supported by this directory".into()),
        }
    }

    /// Every server's current escrow key, as each published it, for
    /// sealing vault session keys to all of them (§7.6.6).
    ///
    /// # Errors
    ///
    /// Any failure.
    fn escrow_servers(&self) -> Result<Vec<(String, tang_pqc::ExchangeKey)>, DirectoryError> {
        Ok(Vec::new())
    }

    /// Publish `server`'s current escrow key, replacing what it published
    /// before.
    ///
    /// # Errors
    ///
    /// Any failure.
    fn publish_escrow_key(
        &self,
        server: &str,
        key: &tang_pqc::ExchangeKey,
    ) -> Result<(), DirectoryError> {
        let _ = (server, key);
        Ok(())
    }

    /// Is `principal`'s entry locked (`nsAccountLock`), or gone?
    ///
    /// # Errors
    ///
    /// Any failure.
    fn principal_locked(&self, principal: &Principal) -> Result<bool, DirectoryError> {
        let _ = principal;
        Ok(true)
    }

    /// Accept a GSS-API token with channel binding `cb` from another
    /// server's anchor exchange (§4.2), returning the initiator principal.
    ///
    /// # Errors
    ///
    /// Any failure; by default the exchange is not supported.
    fn accept_peer(&self, token: &[u8], cb: &[u8; 32]) -> Result<String, DirectoryError> {
        let _ = (token, cb);
        Err("the anchor exchange is not supported".into())
    }

    /// Create host `fqdn` for a verified voucher (§9): refuse an existing
    /// host or a spent `salt`, add the host to `hostgroup` (if not empty),
    /// record the salt as spent, and create keys.
    ///
    /// # Errors
    ///
    /// Any refusal; by default vouchers are not supported.
    fn join_with_voucher(
        &self,
        fqdn: &str,
        hostgroup: &str,
        salt: &[u8; 32],
        enctypes: &[Enctype],
    ) -> Result<Keytab, DirectoryError> {
        let _ = (fqdn, hostgroup, salt, enctypes);
        Err("vouchers are not supported by this directory".into())
    }

    /// Record a trust invitation (the hash of its secret), usable once
    /// until `not_after` (§17.4).
    ///
    /// # Errors
    ///
    /// Any failure; by default trusts are not supported.
    fn add_trust_invitation(
        &self,
        hash: &crate::trust::InvitationHash,
        not_after: u64,
    ) -> Result<(), DirectoryError> {
        let _ = (hash, not_after);
        Err("trusts are not supported by this directory".into())
    }

    /// Use up the invitation with this secret `hash`.
    ///
    /// # Errors
    ///
    /// An unknown, used or expired invitation, or any other failure.
    fn consume_trust_invitation(
        &self,
        hash: &crate::trust::InvitationHash,
    ) -> Result<(), DirectoryError> {
        let _ = hash;
        Err("trusts are not supported by this directory".into())
    }

    /// Record a trust with `partner` and its shared `secret`: create the
    /// cross-realm Kerberos keys (FreeIPA's `trust-add --trust_secret`)
    /// and remember the partner for [`Directory::trusted_realms`].
    ///
    /// # Errors
    ///
    /// Any failure; by default trusts are not supported.
    fn record_trust(&self, partner: &TrustedRealm, secret: &[u8]) -> Result<(), DirectoryError> {
        let _ = (partner, secret);
        Err("trusts are not supported by this directory".into())
    }

    /// Replace a recorded partner's description (refreshed anchors and
    /// servers), keeping its keys.
    ///
    /// # Errors
    ///
    /// An unknown partner, or any other failure.
    fn update_trust(&self, partner: &TrustedRealm) -> Result<(), DirectoryError> {
        let _ = partner;
        Err("trusts are not supported by this directory".into())
    }

    /// The recorded trusted realms.
    ///
    /// # Errors
    ///
    /// Any failure.
    fn trusted_realms(&self) -> Result<Vec<TrustedRealm>, DirectoryError> {
        Ok(Vec::new())
    }
}

