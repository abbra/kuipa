/// Where a leaf landed in a [`Ledger`].
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Appended {
    /// The log.
    pub log: LogId,
    /// The leaf's index.
    pub index: u64,
    /// The leaf's tree hash.
    pub leaf: merkle::Hash,
    /// The leaf's time.
    pub time: u64,
}

/// Where the server records the events of `DESIGN-tlog.md`, implemented
/// by the daemon over its log store.  The server appends after an
/// operation's checks pass and before it answers, so nothing a logged
/// operation releases leaves the server unrecorded; a failed append
/// refuses the request.
pub trait Ledger: Send + Sync + fmt::Debug {
    /// Append a leaf of `kind` about `subject` (hashed into the leaf's
    /// index by the ledger's key) and say where it landed; `None` when
    /// this ledger keeps no log.
    ///
    /// # Errors
    ///
    /// Any storage failure.
    fn append(
        &self,
        kind: Kind,
        subject: &[u8],
        body: &[u8],
    ) -> Result<Option<Appended>, DirectoryError>;

    /// The log's current head, signed with `key` at `now`; none for an
    /// empty log or a ledger that keeps none.
    ///
    /// # Errors
    ///
    /// Any signing failure.
    fn signed_head(
        &self,
        key: &tang_pqc::SigningKey,
        now: u64,
    ) -> Result<Option<SignedHead>, DirectoryError> {
        let _ = (key, now);
        Ok(None)
    }

    /// Up to `max` leaves about `subject` from index `from`, among the
    /// first `size` leaves, each with its inclusion path in that tree.
    ///
    /// # Errors
    ///
    /// Any storage failure, or a size beyond the log.
    fn find(
        &self,
        subject: &[u8],
        from: u64,
        size: u64,
        max: usize,
    ) -> Result<Vec<Entry>, DirectoryError> {
        let _ = (subject, from, size, max);
        Ok(Vec::new())
    }
}

/// A ledger that records nothing: the default, for servers without a log.
#[derive(Clone, Copy, Debug, Default)]
pub struct NoLedger;

impl Ledger for NoLedger {
    fn append(&self, _: Kind, _: &[u8], _: &[u8]) -> Result<Option<Appended>, DirectoryError> {
        Ok(None)
    }
}

/// A refused request.  Send the client an empty `403`; log the reason.
#[derive(Debug)]
pub struct Refusal(DirectoryError);

impl Refusal {
    fn because(reason: impl Into<DirectoryError>) -> Self {
        Self(reason.into())
    }
}

impl fmt::Display for Refusal {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "request refused: {}", self.0)
    }
}

impl std::error::Error for Refusal {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        Some(&*self.0)
    }
}

impl From<tang_pqc::Error> for Refusal {
    fn from(e: tang_pqc::Error) -> Self {
        Self::because(Error::from(e))
    }
}

impl From<Error> for Refusal {
    fn from(e: Error) -> Self {
        Self::because(e)
    }
}

/// Default advertisement validity (7 days), re-signed at half life.
pub const ADVERTISEMENT_VALIDITY: u64 = 7 * 24 * 3600;

/// Cache key of a signed advertisement: the anchor whose proof it
/// carries, the anchor its succession chain starts from, the epoch
/// head it names (§4.8), and a digest of the delegation it carries —
/// head proofs (§4.9) differ per pinned head, so two clients pinning
/// different heads must not share a cached answer.
type AdvKey = (
    Option<Thumbprint>,
    Option<Thumbprint>,
    Option<(u64, crate::epoch::EpochHead)>,
    Option<merkle::Hash>,
);

/// Most claim-log leaves served in one page (§4.9): a page is for
/// filling a gap or auditing, both of which walk forward.
pub const MAX_CLAIM_LOG_PAGE: usize = 4096;

/// One page of an anchor's claim log (§4.9), the answer to
/// `GET /ipa/ku/claim-log/{anchor}?from=`: the leaves after `from`, with
/// the head they lead to.  The leaves are base64url hashes; a claim is
/// found by its own leaf hash, in the anchor exchange or a delegation.
#[derive(Clone, Debug, serde::Serialize, serde::Deserialize)]
pub struct ClaimLogPage {
    /// The anchor whose log this is (base64url thumbprint).
    pub anchor: String,
    /// The size of the log at the head.
    pub size: u64,
    /// The tree hash at the head: 32 bytes (SHA-256) or 48 (SHA-384),
    /// as the anchor's key decides.
    pub root: Vec<u8>,
    /// When the vouch that signed the head expires (Unix seconds).
    pub exp: u64,
    /// The base64url leaf hashes after the page's `from`, oldest first.
    pub leaves: Vec<String>,
    /// The signed vouch of this head (DESIGN-claim-logs.md §4):
    /// base64url `IPSV` v2, public data — it travels in the exchange
    /// and every signature proof — so a reader can check that the head
    /// was signed at all, against the anchor's key from any
    /// advertisement.
    pub vouch: String,
}

impl ClaimLogPage {
    /// The head this page's vouch **proves**: parse the signed vouch,
    /// verify it against the anchor's `key` (policy, signature, anchor,
    /// tree), bind it to this page's anchor and `(size, root)`, and
    /// check the vouch is valid at `at`.  A reader that pinned a thumbprint
    /// pins a head only when a page verifies here (DESIGN-claim-logs.md
    /// §4): the page bytes alone, or an advertisement's `heads` member,
    /// are the server's assertion, not the anchor's.
    ///
    /// # Errors
    ///
    /// [`Error::Malformed`] for a missing or unparsable vouch or anchor,
    /// [`Error::UntrustedAnchor`] for another key or a bad signature,
    /// [`Error::Mismatch`] when the vouch names another anchor or head,
    /// [`Error::Expired`] when the vouch is expired at `at`.
    pub fn verified_head(
        &self,
        key: &VerifyingKey,
        policy: &Policy,
        at: u64,
    ) -> crate::Result<HeadPin> {
        let bytes =
            tang_pqc::b64::decode(&self.vouch).map_err(|_| Error::Malformed("claim log vouch"))?;
        let vouch = SignedVouch::from_bytes(&bytes)?;
        vouch.verify(key, policy)?;
        let anchor = self
            .anchor
            .parse::<Thumbprint>()
            .map_err(|_| Error::Malformed("claim log anchor"))?;
        let v = vouch.vouch();
        if v.anchor != anchor || v.size != self.size || *v.root != *self.root {
            return Err(Error::Mismatch("claim log head"));
        }
        if !crate::delegation::valid_at(v.iat, v.exp, at) {
            return Err(Error::Expired);
        }
        Ok(HeadPin {
            anchor,
            size: self.size,
            root: v.root,
        })
    }
}

/// What the anchor exchange decides (§4.2): this server's delegation, with
/// every trusted anchor's signature, and the trusted anchors.
#[derive(Clone, Debug)]
struct Published {
    delegation: Delegation,
    anchors: Vec<Thumbprint>,
    /// The trusted anchors' signed vouches, by thumbprint: what head
    /// proofs (§4.9) are served from.
    vouches: HashMap<Thumbprint, SignedVouch>,
    /// Trusted realms (§17).
    trusts: Vec<TrustedRealm>,
    /// The anchor epoch log (§4.8), oldest first.
    epoch: Vec<SignedEpoch>,
    /// Signed advertisements by the anchor whose proof they carry, the
    /// anchor their chain of successions starts from, and the epoch head
    /// they name.
    advertisements: HashMap<AdvKey, (SignedAdvertisement, u64)>,
}

/// One IPA server.
#[derive(Debug)]
