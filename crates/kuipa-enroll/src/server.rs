    /// Accept only what `policy` allows from delegations, partners and
    /// session tokens; the default is [`tang_pqc::Policy::default`].
    #[must_use]
    pub fn with_policy(mut self, policy: tang_pqc::Policy) -> Self {
        self.policy = policy;
        self
    }

    /// Record vault, escrow and Keys events in `ledger`; the default
    /// records nothing ([`NoLedger`]).
    #[must_use]
    pub fn with_ledger(mut self, ledger: Arc<dyn Ledger>) -> Self {
        self.ledger = ledger;
        self
    }

    /// Append an event to the ledger, and sign a receipt for where it
    /// landed (none when the ledger keeps no log).
    /// The hash of this server's log: its signing key's
    /// ([`TreeHash::for_signer`](merkle::TreeHash::for_signer)).
    fn tree_hash(&self) -> merkle::TreeHash {
        merkle::TreeHash::for_signer(self.keys.signing.public().alg())
    }

    fn record(&self, kind: Kind, subject: &[u8], body: &[u8]) -> Result<Option<Receipt>, Refusal> {
        let Some(a) = self.ledger.append(kind, subject, body).map_err(Refusal)? else {
            return Ok(None);
        };
        Ok(Some(Receipt::issue(
            &self.keys.signing,
            a.log,
            a.index,
            a.leaf,
            a.time,
        )?))
    }

    /// Record `action` on `vault` as it is about to be stored: the device
    /// added is its newest, and a policy set is recorded by its digest.
    fn record_change(
        &self,
        vault: &Vault,
        action: VaultAction,
        device: Option<String>,
    ) -> Result<Option<Receipt>, Refusal> {
        let device = match action {
            VaultAction::AddDevice => vault.devices.last().map(|d| d.id.clone()),
            _ => device,
        };
        let digest = match action {
            VaultAction::Create
            | VaultAction::SetPolicy
            | VaultAction::Share
            | VaultAction::Unshare => {
                // A policy, or who shares the vault after the change.
                let what = match action {
                    VaultAction::Share | VaultAction::Unshare => vault.sharing_bytes(),
                    _ => serde_json::to_vec(&vault.policy)
                        .map_err(|e| Refusal::because(e.to_string()))?,
                };
                let alg = self.tree_hash();
                merkle::Hash::from_slice(&tang_pqc::primitives::digest(
                    alg.openssl_name(),
                    &[&what],
                )?)?
            }
            _ => merkle::Hash::zero(self.tree_hash()),
        };
        self.record_vault(&vault.id, action, device.as_deref(), digest)
    }

    /// Record the release of a sealed file's server share, by its binding.
    fn record_release(
        &self,
        request: &EscrowRequest,
        device: Option<&crate::vault::Device>,
        opened: &tang_pqc::OpenedRequest<'_>,
    ) -> Result<Option<Receipt>, Refusal> {
        // The release is logged by the escrow binding: the KEM suite's
        // hash, as the log's own is the signer's.
        let binding = BindingHash::from_slice(&opened.ciphertext_hash().map_err(Error::from)?)?;
        let device = device.map(|d| d.id.as_str());
        self.record_vault(request.vault(), VaultAction::Release, device, binding)
    }

    /// Record a vault event about `vault`.
    fn record_vault(
        &self,
        vault: &escrow::VaultId,
        action: VaultAction,
        device: Option<&str>,
        digest: merkle::Hash,
    ) -> Result<Option<Receipt>, Refusal> {
        let event = VaultEvent {
            action,
            device: device.map(str::to_owned),
            digest,
        };
        self.record(action.kind(), vault.as_bytes(), &event.to_bytes())
    }

    /// Replace the delegation and the trusted anchors, as decided by the
    /// anchor exchange, with the trusted anchors' signed vouches (the
    /// claim logs head proofs are served from, §4.9).
    pub fn publish(
        &self,
        delegation: Delegation,
        anchors: Vec<Thumbprint>,
        vouches: HashMap<Thumbprint, SignedVouch>,
    ) {
        let mut p = self
            .published
            .write()
            .unwrap_or_else(PoisonError::into_inner);
        if p.delegation != delegation || p.anchors != anchors || p.vouches != vouches {
            p.delegation = delegation;
            p.anchors = anchors;
            p.vouches = vouches;
            p.advertisements.clear();
        }
    }

    /// Replace the trusted realms this server advertises (§17).
    pub fn publish_trusts(&self, trusts: Vec<TrustedRealm>) {
        let mut p = self
            .published
            .write()
            .unwrap_or_else(PoisonError::into_inner);
        if p.trusts != trusts {
            p.trusts = trusts;
            p.advertisements.clear();
        }
    }

    /// The trusted realms this server publishes.
    #[must_use]
    pub fn trusts(&self) -> Vec<TrustedRealm> {
        self.published
            .read()
            .unwrap_or_else(PoisonError::into_inner)
            .trusts
            .clone()
    }

    /// Replace the anchor epoch log (§4.8): the whole chain, oldest
    /// first, as maintained by the anchor exchange.
    pub fn publish_epoch(&self, chain: Vec<SignedEpoch>) {
        let mut p = self
            .published
            .write()
            .unwrap_or_else(PoisonError::into_inner);
        if p.epoch != chain {
            p.epoch = chain;
            p.advertisements.clear();
        }
    }

    /// The head of this server's anchor epoch log, if it has one.
    #[must_use]
    pub fn epoch_head(&self) -> Option<(u64, crate::epoch::EpochHead)> {
        self.published()
            .epoch
            .last()
            .and_then(|e| e.statement().ok())
            .and_then(|s| Some((s.seq(), s.head().ok()?)))
    }

    /// The chain entries after sequence number `from`, at most
    /// [`MAX_EPOCH_FETCH`]: the answer to `GET anchor-log` (§4.8).
    #[must_use]
    pub fn epoch_log(&self, from: u64) -> Vec<SignedEpoch> {
        let p = self.published();
        p.epoch
            .iter()
            .skip_while(|e| e.statement().is_ok_and(|s| s.seq() <= from))
            .take(MAX_EPOCH_FETCH)
            .cloned()
            .collect()
    }

    /// The current delegation, with every signature.
    #[must_use]
    pub fn delegation(&self) -> Delegation {
        self.published().delegation
    }

    /// The trusted anchors.
    #[must_use]
    pub fn anchors(&self) -> Vec<Thumbprint> {
        self.published().anchors
    }

    /// A trusted anchor's signed vouch, if it published one (§4.9).
    #[must_use]
    pub fn vouch(&self, anchor: &Thumbprint) -> Option<SignedVouch> {
        self.published().vouches.get(anchor).cloned()
    }

    /// The trusted anchors' signed vouches (§4.9), by thumbprint.
    #[must_use]
    pub fn vouches(&self) -> HashMap<Thumbprint, SignedVouch> {
        self.published().vouches
    }

    /// The trusted anchors' current vouch heads (§4.9).
    #[must_use]
    pub fn heads(&self) -> Vec<HeadPin> {
        let p = self.published();
        p.anchors
            .iter()
            .filter_map(|a| {
                p.vouches.get(a).map(|v| HeadPin {
                    anchor: *a,
                    size: v.vouch().size,
                    root: v.vouch().root,
                })
            })
            .collect()
    }

    /// One anchor's claim log page (§4.9): the leaves after index
    /// `from`, oldest first, at most [`MAX_CLAIM_LOG_PAGE`], with the
    /// head they lead to and its expiry.  `None` if this server does not
    /// know the anchor or holds no vouch of it.
    #[must_use]
    pub fn claim_log(&self, anchor: &Thumbprint, from: u64) -> Option<ClaimLogPage> {
        let vouch = self.vouch(anchor)?;
        let v = vouch.vouch();
        let from = usize::try_from(from).unwrap_or(usize::MAX);
        let leaves = vouch
            .leaves()
            .iter()
            .skip(from)
            .take(MAX_CLAIM_LOG_PAGE)
            .map(|l| tang_pqc::b64::encode(l))
            .collect();
        Some(ClaimLogPage {
            anchor: anchor.to_string(),
            size: v.size,
            root: v.root.to_vec(),
            exp: v.exp,
            leaves,
            vouch: tang_pqc::b64::encode(&vouch.to_bytes()),
        })
    }

    fn published(&self) -> Published {
        self.published
            .read()
            .unwrap_or_else(PoisonError::into_inner)
            .clone()
    }

