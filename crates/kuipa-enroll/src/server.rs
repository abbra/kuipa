/// A refused request.  Send the client an empty `403`; log the reason.
#[derive(Debug)]
pub struct Refusal(DirectoryError);

impl Refusal {
    fn because(reason: impl Into<DirectoryError>) -> Self {
        Self(reason.into())
    }
}

impl fmt::Display for Refusal {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "request refused: {}", self.0)
    }
}

impl std::error::Error for Refusal {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        Some(&*self.0)
    }
}

impl From<tang_pqc::Error> for Refusal {
    fn from(e: tang_pqc::Error) -> Self {
        Self::because(Error::from(e))
    }
}

impl From<Error> for Refusal {
    fn from(e: Error) -> Self {
        Self::because(e)
    }
}

/// Default advertisement validity (7 days), re-signed at half life.
pub const ADVERTISEMENT_VALIDITY: u64 = 7 * 24 * 3600;

/// Cache key of a signed advertisement: the anchor whose proof it
/// carries, the anchor its succession chain starts from, and the epoch
/// head it names (§4.8).
type AdvKey = (
    Option<Thumbprint>,
    Option<Thumbprint>,
    Option<(u64, [u8; 32])>,
);

/// What the anchor exchange decides (§4.2): this server's delegation, with
/// every trusted anchor's signature, and the trusted anchors.
#[derive(Clone, Debug)]
struct Published {
    delegation: Delegation,
    anchors: Vec<Thumbprint>,
    /// Trusted realms (§17).
    trusts: Vec<TrustedRealm>,
    /// The anchor epoch log (§4.8), oldest first.
    epoch: Vec<SignedEpoch>,
    /// Signed advertisements by the anchor whose proof they carry, the
    /// anchor their chain of successions starts from, and the epoch head
    /// they name.
    advertisements: HashMap<AdvKey, (SignedAdvertisement, u64)>,
}

/// One IPA server.
#[derive(Debug)]
pub struct EnrollServer {
    keys: ServerKeys,
    info: RealmInfo,
    published: RwLock<Published>,
}

const STAGE_MAGIC: [u8; 4] = *b"IPSP";

impl EnrollServer {
    /// A server with `keys` and `delegation`, publishing `info`.
    #[must_use]
    pub fn new(keys: ServerKeys, info: RealmInfo, delegation: Delegation) -> Self {
        let anchors = info.anchors.clone();
        let trusts = info.trusts.clone();
        Self {
            keys,
            info,
            published: RwLock::new(Published {
                delegation,
                anchors,
                trusts,
                advertisements: HashMap::new(),
                epoch: Vec::new(),
            }),
        }
    }

    /// Replace the delegation and the trusted anchors, as decided by the
    /// anchor exchange.
    pub fn publish(&self, delegation: Delegation, anchors: Vec<Thumbprint>) {
        let mut p = self
            .published
            .write()
            .unwrap_or_else(PoisonError::into_inner);
        if p.delegation != delegation || p.anchors != anchors {
            p.delegation = delegation;
            p.anchors = anchors;
            p.advertisements.clear();
        }
    }

    /// Replace the trusted realms this server advertises (§17).
    pub fn publish_trusts(&self, trusts: Vec<TrustedRealm>) {
        let mut p = self
            .published
            .write()
            .unwrap_or_else(PoisonError::into_inner);
        if p.trusts != trusts {
            p.trusts = trusts;
            p.advertisements.clear();
        }
    }

    /// The trusted realms this server publishes.
    #[must_use]
    pub fn trusts(&self) -> Vec<TrustedRealm> {
        self.published
            .read()
            .unwrap_or_else(PoisonError::into_inner)
            .trusts
            .clone()
    }

    /// Replace the anchor epoch log (§4.8): the whole chain, oldest
    /// first, as maintained by the anchor exchange.
    pub fn publish_epoch(&self, chain: Vec<SignedEpoch>) {
        let mut p = self
            .published
            .write()
            .unwrap_or_else(PoisonError::into_inner);
        if p.epoch != chain {
            p.epoch = chain;
            p.advertisements.clear();
        }
    }

    /// The head of this server's anchor epoch log, if it has one.
    #[must_use]
    pub fn epoch_head(&self) -> Option<(u64, [u8; 32])> {
        self.published()
            .epoch
            .last()
            .and_then(|e| e.statement().ok())
            .and_then(|s| Some((s.seq(), s.head().ok()?)))
    }

    /// The chain entries after sequence number `from`, at most
    /// [`MAX_EPOCH_FETCH`]: the answer to `GET anchor-log` (§4.8).
    #[must_use]
    pub fn epoch_log(&self, from: u64) -> Vec<SignedEpoch> {
        let p = self.published();
        p.epoch
            .iter()
            .skip_while(|e| e.statement().is_ok_and(|s| s.seq() <= from))
            .take(MAX_EPOCH_FETCH)
            .cloned()
            .collect()
    }

    /// The current delegation, with every signature.
    #[must_use]
    pub fn delegation(&self) -> Delegation {
        self.published().delegation
    }

    /// The trusted anchors.
    #[must_use]
    pub fn anchors(&self) -> Vec<Thumbprint> {
        self.published().anchors
    }

    fn published(&self) -> Published {
        self.published
            .read()
            .unwrap_or_else(PoisonError::into_inner)
            .clone()
    }

    /// The server's keys.
    #[must_use]
    pub fn keys(&self) -> &ServerKeys {
        &self.keys
    }

    /// The realm metadata it publishes.
    #[must_use]
    pub fn info(&self) -> &RealmInfo {
        &self.info
    }

    /// `GET /ipa/ku/adv`: the advertisement, re-signed at half life.  Its
    /// delegation carries one signature: by the first of `wanted` (the
    /// anchors the client pins) that signed it, else by this server's own
    /// anchor (§4.3); for a client that pins only rotated anchors, with the
    /// successions that lead to the signer (§4.7).
    ///
    /// # Errors
    ///
    /// A signing error.
    pub fn advertisement(&self, wanted: &[Thumbprint]) -> crate::Result<SignedAdvertisement> {
        let now = unix_seconds(SystemTime::now());
        let published = self.published();
        let epoch = published
            .epoch
            .last()
            .and_then(|e| e.statement().ok())
            .and_then(|s| Some((s.seq(), s.head().ok()?)));
        let delegation = published.delegation.select(wanted);
        let signer = (
            delegation
                .signers(&tang_pqc::Policy::default())
                .first()
                .copied(),
            delegation
                .successions()
                .first()
                .and_then(|s| s.statement().ok())
                .map(|s| s.old),
            epoch,
        );
        if let Some((adv, iat)) = published.advertisements.get(&signer)
            && now.saturating_sub(*iat) < ADVERTISEMENT_VALIDITY / 2
        {
            return Ok(adv.clone());
        }
        let info = RealmInfo {
            anchors: published.anchors.clone(),
            trusts: published.trusts.clone(),
            ..self.info.clone()
        };
        let adv = self.keys.advertisement(
            &info,
            &delegation,
            now,
            now + ADVERTISEMENT_VALIDITY,
            epoch,
        )?;
        let mut p = self
            .published
            .write()
            .unwrap_or_else(PoisonError::into_inner);
        if p.delegation == published.delegation
            && p.anchors == published.anchors
            && p.trusts == published.trusts
            && p.epoch == published.epoch
        {
            p.advertisements.insert(signer, (adv.clone(), now));
        }
        Ok(adv)
    }

    /// Answer a join, rekey, stage or registration request received at the
    /// endpoint of `request.operation()`.
    ///
    /// # Errors
    ///
    /// A [`Refusal`] for any failure.
    pub fn handle(
        &self,
        request: &Request,
        directory: &dyn Directory,
    ) -> Result<Response, Refusal> {
        if request.realm() != self.info.realm {
            return Err(Refusal::because("wrong realm"));
        }
        let key = self
            .keys
            .join_key(request.kid())
            .filter(|k| k.public().alg() == request.alg())
            .ok_or_else(|| Refusal::because("unknown join key"))?;
        let ss = key.decapsulate(request.ciphertext())?;
        let t = request.transcript(self.keys.signing.public().thumbprint())?;
        let body = request.open_body(ss.as_ref(), &t)?;
        let cb = channel_binding(request.alg(), ss.as_ref(), &t)?;
        let fqdn = request.fqdn();
        let enctypes = request.enctypes();
        let token = body.authenticator.as_ref();
        let principal = Principal::host(fqdn, &self.info.realm);
        let mut kerberos = None;

        let payload = match (request.operation(), request.auth_type()) {
            (Operation::Join, AuthType::Otp) => {
                let keytab = directory
                    .join_with_otp(fqdn, token, enctypes)
                    .map_err(Refusal)?;
                self.enrollment(keytab, directory)?.to_bytes()?
            }
            (Operation::Join, AuthType::Voucher) => {
                let voucher = Voucher::parse(token)?;
                let key = self
                    .keys
                    .vouchers
                    .iter()
                    .find(|k| k.thumbprint() == voucher.key())
                    .ok_or_else(|| Refusal::because("unknown voucher key"))?;
                let ephemeral = crate::voucher::binding(request.ephemeral_key())?;
                let now = unix_seconds(SystemTime::now());
                let claims = voucher.verify(key, &self.info.realm, fqdn, &ephemeral, now)?;
                let keytab = directory
                    .join_with_voucher(fqdn, &claims.hostgroup, voucher.salt(), enctypes)
                    .map_err(Refusal)?;
                self.enrollment(keytab, directory)?.to_bytes()?
            }
            (Operation::Join, AuthType::Kerberos) => {
                let (keytab, binding) = directory
                    .join_with_gss(fqdn, token, &cb, enctypes)
                    .map_err(Refusal)?;
                kerberos = Some(binding);
                self.enrollment(keytab, directory)?.to_bytes()?
            }
            (Operation::Rekey, AuthType::Kerberos) => {
                let (keytab, binding) = directory
                    .rekey_with_gss(fqdn, token, &cb, enctypes)
                    .map_err(Refusal)?;
                kerberos = Some(binding);
                self.enrollment(keytab, directory)?.to_bytes()?
            }
            (Operation::Stage, AuthType::Kerberos) => {
                let (payload, binding) = self.stage(request, &body, &cb, directory)?;
                kerberos = Some(binding);
                payload
            }
            (Operation::Register, AuthType::Kerberos) => {
                return self.register(request, ss.as_ref(), &t, &body, directory);
            }
            (Operation::Vault, AuthType::Kerberos) => {
                return self.vault_op(request, ss.as_ref(), &t, &body, directory);
            }
            (op, auth) => {
                return Err(Refusal::because(format!(
                    "{op:?} with {auth:?} is not supported"
                )));
            }
        };
        if !body.registrations.is_empty() && request.operation() != Operation::Stage {
            directory
                .register_escrow(&principal, &body.registrations)
                .map_err(Refusal)?;
        }
        Ok(request.respond(ss.as_ref(), &t, kerberos.as_ref(), payload.as_ref())?)
    }

    /// Stage a host (§8.3): keys from the directory, packed into a bundle
    /// for the recipient the parameters name.
    fn stage(
        &self,
        request: &Request,
        body: &RequestBody,
        cb: &[u8; 32],
        directory: &dyn Directory,
    ) -> Result<(native_ossl::util::SecretBuf, KerberosBinding), Refusal> {
        let params = StageParams::from_bytes(&body.extra)?;
        let staged = Staged {
            not_after: params.not_after,
            recipient: params.recipient.as_ref().map(|k| *k.kid()),
        };
        let (keytab, binding) = directory
            .stage_with_gss(
                request.fqdn(),
                body.authenticator.as_ref(),
                cb,
                request.enctypes(),
                &staged,
            )
            .map_err(Refusal)?;
        let enrollment = self.enrollment(keytab, directory)?;
        let recipient = match (params.mode, &params.recipient) {
            (crate::bundle::Mode::MachineKey, Some(k)) => Recipient::MachineKey(k),
            (crate::bundle::Mode::Secret, _) => Recipient::Secret,
            _ => Recipient::SignedOnly,
        };
        let now = unix_seconds(SystemTime::now());
        let (bundle, secret) = Bundle::create(
            &self.keys,
            &self.delegation().select(&[]),
            request.alg(),
            recipient,
            &enrollment,
            now,
            params.not_after,
        )?;
        let mut w = Writer::new(STAGE_MAGIC);
        w.bytes(&bundle.to_bytes())
            .bytes(secret.as_ref().map_or(&[][..], |s| s.as_bytes()));
        Ok((native_ossl::util::SecretBuf::new(w.finish()), binding))
    }

    /// Answer a registration (§7.5): change the bindings of its principal
    /// as the directory authorises, and acknowledge.
    fn register(
        &self,
        request: &Request,
        ss: &[u8],
        t: &[u8],
        body: &RequestBody,
        directory: &dyn Directory,
    ) -> Result<Response, Refusal> {
        let params = RegisterParams::from_bytes(&body.extra)?;
        if params.principal.realm() != self.info.realm {
            return Err(Refusal::because("wrong realm"));
        }
        let cb = channel_binding(request.alg(), ss, t)?;
        let token = body.authenticator.as_ref();
        let binding = directory
            .register_with_gss(&params, &body.registrations, token, &cb)
            .map_err(Refusal)?;
        Ok(request.respond(ss, t, Some(&binding), &params.acknowledgement())?)
    }

    /// Answer an owner's vault operation (§7.6): authenticate the owner
    /// by their ticket, apply the realm limits, store, and answer with
    /// signed descriptors.
    fn vault_op(
        &self,
        request: &Request,
        ss: &[u8],
        t: &[u8],
        body: &RequestBody,
        directory: &dyn Directory,
    ) -> Result<Response, Refusal> {
        let cb = channel_binding(request.alg(), ss, t)?;
        let accepted = directory
            .accept_user(body.authenticator.as_ref(), &cb)
            .map_err(Refusal)?;
        let owner: Principal = accepted.principal.parse()?;
        if owner.realm() != self.info.realm {
            return Err(Refusal::because("wrong realm"));
        }
        let op = VaultOp::from_bytes(&body.extra)?;
        let now = unix_seconds(SystemTime::now());
        let delegation = self.delegation();
        let (mut vaults, session, released) = match op {
            VaultOp::Unlock {
                name,
                device,
                offline,
            } => {
                let (vault, token, released) =
                    self.start_session(&owner, &name, &device, offline, now, directory)?;
                (vec![vault], Some(token), released)
            }
            op => (
                Self::apply_vault_op(&owner, op, now, directory)?,
                None,
                None,
            ),
        };
        for v in &mut vaults {
            if self.maintain_epochs(v, now, directory)? {
                directory.vault_update(v).map_err(Refusal)?;
            }
        }
        let max_age = directory.vault_limits().map_err(Refusal)?.descriptor_age;
        let descriptors = vaults
            .iter()
            .map(|v| {
                // Descriptors carry each epoch's public key, never its slots.
                let mut public = v.clone();
                for k in &mut public.session_keys {
                    k.slots.clear();
                }
                Descriptor::sign(
                    &self.keys.signing,
                    &delegation,
                    &self.info.realm,
                    &public,
                    now,
                    max_age,
                )
            })
            .collect::<crate::Result<Vec<_>>>()?;
        let reply = Reply {
            descriptors,
            session,
            released,
        };
        Ok(request.respond(ss, t, Some(&accepted.binding), &reply.to_bytes())?)
    }

    /// Every server's escrow key, this one's own current key included
    /// (and published, when the directory did not have it yet).
    fn escrow_servers(
        &self,
        directory: &dyn Directory,
    ) -> Result<Vec<(String, tang_pqc::ExchangeKey)>, Refusal> {
        let mut servers = directory.escrow_servers().map_err(Refusal)?;
        let own = self
            .keys
            .escrow
            .first()
            .ok_or_else(|| Refusal::because("no escrow key"))?
            .public()
            .clone();
        if !servers.iter().any(|(_, k)| k.kid() == own.kid()) {
            directory
                .publish_escrow_key(&self.info.server, &own)
                .map_err(Refusal)?;
            servers.retain(|(s, _)| s != &self.info.server);
            servers.push((self.info.server.clone(), own));
        }
        Ok(servers)
    }

    /// For a vault with offline sessions: start the next epoch when the
    /// current one has run its length, and seal every key this server can
    /// open to servers that have no slot yet.  Returns whether it changed.
    fn maintain_epochs(
        &self,
        vault: &mut Vault,
        now: u64,
        directory: &dyn Directory,
    ) -> Result<bool, Refusal> {
        if vault.state != State::Enabled || vault.policy.sessions.offline.is_none() {
            return Ok(false);
        }
        let servers = self.escrow_servers(directory)?;
        let mut changed = false;
        for key in &mut vault.session_keys {
            if let Ok(pair) = key.open(&vault.id, &self.keys.escrow) {
                changed |= key.add_slots(&vault.id, &pair, &servers)?;
            }
        }
        let length = vault.policy.sessions.epoch.unwrap_or(DEFAULT_EPOCH);
        let due = vault
            .session_keys
            .last()
            .is_none_or(|k| now >= k.started.saturating_add(length));
        if due {
            let epoch = vault.session_keys.last().map_or(1, |k| k.epoch + 1);
            vault
                .session_keys
                .push(SessionKey::generate(&vault.id, epoch, now, &servers)?);
            eprintln!("kuipad: vault {} starts session epoch {epoch}", vault.id);
            changed = true;
        }
        Ok(changed)
    }

    /// Start a session for `device` of `owner`'s vault `name`, as long as
    /// its policy allows (and no longer than the vault): a re-authentication
    /// token, or offline the vault's session keys released to the device.
    fn start_session(
        &self,
        owner: &Principal,
        name: &str,
        device: &str,
        offline: bool,
        now: u64,
        directory: &dyn Directory,
    ) -> Result<(Vault, SessionToken, Option<ReleasedKeys>), Refusal> {
        let mut vault = directory
            .vaults_of(owner)
            .map_err(Refusal)?
            .into_iter()
            .find(|v| v.name == name)
            .ok_or_else(|| Refusal::because(format!("{owner} has no vault {name:?}")))?;
        if vault.state != State::Enabled {
            return Err(Refusal::because("the vault is revoked"));
        }
        let sessions = &vault.policy.sessions;
        let length = if offline {
            if !directory.vault_limits().map_err(Refusal)?.offline_sessions {
                return Err(Refusal::because(
                    "the realm does not allow offline sessions",
                ));
            }
            sessions.offline
        } else {
            sessions.reauth
        }
        .ok_or_else(|| Refusal::because("the vault's policy allows no such session"))?;
        if offline && self.maintain_epochs(&mut vault, now, directory)? {
            directory.vault_update(&vault).map_err(Refusal)?;
        }
        let registered = vault
            .devices
            .iter()
            .find(|d| d.id == device)
            .ok_or_else(|| Refusal::because("the device is not registered"))?;
        let device = registered.thumbprint()?;
        let released = if offline {
            if !directory
                .vault_unlock(&vault.id, &self.info.server, vault.policy.max_unlocks)
                .map_err(Refusal)?
            {
                return Err(Refusal::because("the vault's unlock limit is reached"));
            }
            let keys = vault
                .session_keys
                .iter()
                .map(|k| Ok((k.epoch, k.open(&vault.id, &self.keys.escrow)?)))
                .collect::<crate::Result<Vec<_>>>()?;
            Some(ReleasedKeys::seal(&registered.public()?, &vault.id, &keys)?)
        } else {
            None
        };
        let not_after = vault
            .policy
            .not_after
            .map_or(now + length, |end| end.min(now + length));
        let token = SessionToken::sign(
            &self.keys.signing,
            &self.delegation(),
            vault.id,
            &vault.owner,
            device,
            not_after,
        )?;
        eprintln!(
            "kuipad: {owner} started {} session for vault {} until {not_after}",
            if offline { "an offline" } else { "a" },
            vault.id
        );
        Ok((vault, token, released))
    }

    fn apply_vault_op(
        owner: &Principal,
        op: VaultOp,
        now: u64,
        directory: &dyn Directory,
    ) -> Result<Vec<Vault>, Refusal> {
        let limits = directory.vault_limits().map_err(Refusal)?;
        let mine = directory.vaults_of(owner).map_err(Refusal)?;
        let named = |name: &str| {
            mine.iter()
                .find(|v| v.name == name)
                .cloned()
                .ok_or_else(|| Refusal::because(format!("{owner} has no vault {name:?}")))
        };
        let vault = match op {
            VaultOp::List => return Ok(mine),
            VaultOp::Unlock { .. } => unreachable!("sessions are started by vault_op"),
            VaultOp::Show { name } => return Ok(vec![named(&name)?]),
            VaultOp::Create { name, mut policy } => {
                if mine.iter().any(|v| v.name == name) {
                    return Err(Refusal::because(format!("vault {name:?} exists")));
                }
                if mine.len() >= limits.max_vaults {
                    return Err(Refusal::because("too many vaults"));
                }
                limits.apply(&mut policy, now)?;
                let mut id = [0u8; 16];
                native_ossl::rand::Rand::fill(&mut id).map_err(Error::from)?;
                let vault = Vault {
                    id: escrow::VaultId::from_bytes(id),
                    owner: owner.to_string(),
                    name,
                    policy,
                    devices: Vec::new(),
                    state: State::Enabled,
                    unlocks: 0,
                    session_keys: Vec::new(),
                };
                directory.vault_add(&vault).map_err(Refusal)?;
                return Ok(vec![vault]);
            }
            VaultOp::SetPolicy { name, mut policy } => {
                let mut vault = named(&name)?;
                limits.apply(&mut policy, now)?;
                vault.policy = policy;
                vault
            }
            VaultOp::AddDevice {
                name,
                label,
                kind,
                alg,
                key,
            } => {
                let mut vault = named(&name)?;
                if vault.devices.len() >= limits.max_devices {
                    return Err(Refusal::because("too many devices"));
                }
                let public = tang_pqc::ExchangeKey::from_bytes(
                    tang_pqc::KemAlg::from_id(alg).map_err(Error::from)?,
                    &tang_pqc::b64::decode(&key).map_err(Error::from)?,
                )
                .map_err(Error::from)?;
                // No attestation is verified yet: every device is `any`.
                let device = crate::vault::Device::new(&public, &label, kind, now);
                if vault.devices.iter().any(|d| d.id == device.id) {
                    return Err(Refusal::because("device already registered"));
                }
                vault.devices.push(device);
                vault
            }
            VaultOp::RemoveDevice { name, id } => {
                let mut vault = named(&name)?;
                let before = vault.devices.len();
                vault.devices.retain(|d| d.id != id);
                if vault.devices.len() == before {
                    return Err(Refusal::because("no such device"));
                }
                vault
            }
            VaultOp::Revoke { name } => {
                let mut vault = named(&name)?;
                vault.state = State::Revoked;
                vault
            }
        };
        directory.vault_update(&vault).map_err(Refusal)?;
        Ok(vec![vault])
    }

    fn enrollment(&self, keytab: Keytab, directory: &dyn Directory) -> Result<Enrollment, Refusal> {
        let anchors = self.anchors();
        let epoch = self.epoch_head();
        Ok(Enrollment {
            config: RealmConfig {
                realm: self.info.realm.clone(),
                domain: self.info.domain.clone(),
                basedn: self.info.basedn.clone(),
                issuer: self.info.server.clone(),
                servers: directory.servers().map_err(Refusal)?,
            },
            keytab,
            ca_certs: directory.ca_certificates().map_err(Refusal)?,
            pkinit_anchors: self.info.pkinit_anchors.clone(),
            anchors,
            epoch_seq: epoch.map_or(0, |(seq, _)| seq),
            epoch_head: epoch.map_or([0; 32], |(_, head)| head),
        })
    }

    /// This realm as a trust partner sees it: realm, domain, servers and
    /// trusted anchors.
    #[must_use]
    pub fn as_partner(&self) -> TrustedRealm {
        TrustedRealm {
            realm: self.info.realm.clone(),
            domain: self.info.domain.clone(),
            servers: self.info.servers.clone(),
            anchors: self.anchors(),
        }
    }

    /// `POST /ipa/ku/trust/{kid}`: establish a trust with the requesting
    /// realm (§17.4): check the invitation, the requesting server's
    /// delegation and signature, record the trust with the derived secret,
    /// and answer with this realm's description.
    ///
    /// # Errors
    ///
    /// A [`Refusal`] for any failure.
    pub fn establish_trust(
        &self,
        request: &TrustRequest,
        directory: &dyn Directory,
    ) -> Result<TrustResponse, Refusal> {
        if request.realm() != self.info.realm {
            return Err(Refusal::because("wrong realm"));
        }
        let key = self
            .keys
            .trust_key(request.kid())
            .filter(|k| k.public().alg() == request.alg())
            .ok_or_else(|| Refusal::because("unknown trust key"))?;
        let ss = key.decapsulate(request.ciphertext())?;
        let t = request.transcript(self.keys.signing.public().thumbprint())?;
        let body = request.open(ss.as_ref(), &t)?;
        directory
            .consume_trust_invitation(&trust::secret_hash(body.secret.as_ref())?)
            .map_err(Refusal)?;
        let partner = body.partner;
        if partner.realm != request.initiator() {
            return Err(Refusal::because("the request and its realm disagree"));
        }
        partner.validate_for(&self.info.realm, &self.anchors())?;
        let now = unix_seconds(SystemTime::now());
        let delegation =
            body.delegation
                .verify_at(&partner.anchors, &tang_pqc::Policy::default(), now)?;
        let signer = tang_pqc::VerifyingKey::from_jwk_json(body.signer_key.as_bytes())?;
        if delegation.realm != partner.realm || &delegation.key != signer.thumbprint() {
            return Err(Refusal::because(
                "the request is not signed by a server of its realm",
            ));
        }
        signer.verify_with_context(&t, trust::SIGN_CONTEXT, &body.signature)?;
        let (response, secret) = request.respond(ss.as_ref(), &t, &self.as_partner())?;
        directory
            .record_trust(&partner, secret.as_ref())
            .map_err(Refusal)?;
        Ok(response)
    }

    /// `POST /ipa/ku/rec/{kid}`: unseal a registered binding (§7.2).
    ///
    /// # Errors
    ///
    /// A [`Refusal`] for any failure, including an unregistered binding or
    /// a disabled host.
    pub fn recover(
        &self,
        request: &EscrowRequest,
        directory: &dyn Directory,
    ) -> Result<Recovered, Refusal> {
        let recovery = request.recovery();
        let key = self
            .keys
            .escrow_key(recovery.kid())
            .ok_or_else(|| Refusal::because("unknown escrow key"))?;
        if request.principal().realm() != self.info.realm {
            return Err(Refusal::because("wrong realm"));
        }
        let opened = recovery
            .open(key, escrow::DOMAIN)
            .map_err(|_| Refusal::because("request does not open"))?;
        opened
            .verify_commitment(
                &escrow::commitment_data(request.principal(), request.vault()),
                request.commitment(),
            )
            .map_err(|_| Refusal::because("the binding is not committed to this vault"))?;
        let Some(kind) = request.vault().machine_kind(request.principal())? else {
            return self.recover_vault(request, opened, directory);
        };
        let binding = opened.ciphertext_hash().map_err(Error::from)?;
        if !directory
            .escrow_allowed(request.principal(), kind, &binding)
            .map_err(Refusal)?
        {
            return Err(Refusal::because(
                "binding not registered or its principal disabled",
            ));
        }
        Ok(Recovered::Plain(opened.respond().map_err(Error::from)?))
    }

    /// The vault half of [`recover`](Self::recover): check the vault and
    /// its owner, then the policy's factors, and answer to the device.
    fn recover_vault(
        &self,
        request: &EscrowRequest,
        opened: tang_pqc::OpenedRequest<'_>,
        directory: &dyn Directory,
    ) -> Result<Recovered, Refusal> {
        let vault = directory
            .vault_get(request.vault())
            .map_err(Refusal)?
            .ok_or_else(|| Refusal::because(format!("unknown vault {}", request.vault())))?;
        let owner = request.principal();
        if vault.owner != owner.to_string() {
            return Err(Refusal::because("the vault has another owner"));
        }
        if vault.state != State::Enabled {
            return Err(Refusal::because("the vault is revoked"));
        }
        if directory.principal_locked(owner).map_err(Refusal)? {
            return Err(Refusal::because("the owner is locked or gone"));
        }
        let now = unix_seconds(SystemTime::now());
        if vault.policy.not_after.is_some_and(|t| now > t) {
            return Err(Refusal::because("the vault has expired"));
        }
        let factors = &vault.policy.factors;
        if factors.passkey {
            return Err(Refusal::because("the passkey factor is not supported yet"));
        }
        let in_session = !request.session().is_empty();
        if in_session {
            // A session stands in for the ticket: checked here, with the
            // device it is bound to checked below.
            if vault.policy.sessions.reauth.is_none() {
                return Err(Refusal::because("the vault's policy allows no sessions"));
            }
            let device = request
                .device()
                .ok_or_else(|| Refusal::because("a session needs its device"))?;
            SessionToken::from_bytes(request.session())?
                .check(
                    &self.info.realm,
                    &self.anchors(),
                    &tang_pqc::Policy::default(),
                    request.vault(),
                    &vault.owner,
                    device,
                    now,
                )
                .map_err(|e| Refusal::because(format!("session: {e}")))?;
        } else if factors.ticket {
            if request.ticket().is_empty() {
                return Err(Refusal::because("the vault needs the owner's ticket"));
            }
            let cb = request.ticket_binding()?;
            let accepted = directory
                .accept_user(request.ticket(), &cb)
                .map_err(Refusal)?;
            if accepted.principal != vault.owner {
                return Err(Refusal::because("the ticket is not the owner's"));
            }
            if !vault
                .policy
                .ticket_delegation
                .accepts(accepted.transited.as_deref())
            {
                return Err(Refusal::because(match &accepted.transited {
                    Some(t) => format!("a ticket delegated through {t:?} is not accepted"),
                    None => "the ticket's delegation cannot be checked".to_owned(),
                }));
            }
        }
        let device = match request.device() {
            Some(id) => Some(
                vault
                    .device(id)
                    .ok_or_else(|| Refusal::because("the device is not registered"))?,
            ),
            None => None,
        };
        if let Some(level) = factors.device {
            let device = device.ok_or_else(|| Refusal::because("the vault needs a device"))?;
            if device.level < level {
                return Err(Refusal::because("the device's level is too low"));
            }
        }
        if !directory
            .vault_unlock(request.vault(), &self.info.server, vault.policy.max_unlocks)
            .map_err(Refusal)?
        {
            return Err(Refusal::because("the vault's unlock limit is reached"));
        }
        let response = opened.respond().map_err(Error::from)?;
        Ok(match device {
            Some(d) => Recovered::Device(VaultAnswer::seal(&d.public()?, request, &response)?),
            None => Recovered::Plain(response),
        })
    }
}

/// Decode a stage response payload into the bundle and, in mode B, the
/// secret that opens it.
///
/// # Errors
///
/// [`Error::Malformed`].
pub fn parse_stage_result(
    payload: &[u8],
) -> crate::Result<(Bundle, Option<crate::enrollment::Secret>)> {
    let mut r = tang_pqc::wire::Reader::new(payload, STAGE_MAGIC, "stage result")?;
    let bundle = Bundle::from_bytes(r.bytes()?)?;
    let secret = r.bytes()?;
    r.finish()?;
    Ok((
        bundle,
        (!secret.is_empty()).then(|| crate::enrollment::Secret::new(secret)),
    ))
}
